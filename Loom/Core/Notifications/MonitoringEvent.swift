import Foundation

/// Represents a quota alert threshold level.
public enum QuotaThreshold: RawRepresentable, CaseIterable, Equatable, Hashable, Sendable {
    case fifteenPercent
    case fivePercent

    public var rawValue: String {
        switch self {
        case .fifteenPercent: return "15%"
        case .fivePercent: return "5%"
        }
    }

    public init?(rawValue: String) {
        switch rawValue {
        case "15%", "15", "0.15":
            self = .fifteenPercent
        case "5%", "5", "0.05":
            self = .fivePercent
        default:
            return nil
        }
    }

    public var fraction: Double {
        switch self {
        case .fifteenPercent: return 0.15
        case .fivePercent: return 0.05
        }
    }

    public var percentage: Double {
        switch self {
        case .fifteenPercent: return 15.0
        case .fivePercent: return 5.0
        }
    }
}

/// Core system events generated by monitoring and evaluation subsystems.
public enum MonitoringEvent: Equatable, Hashable, Sendable {
    /// Fired when an observed remaining quota crosses below a configured threshold.
    case quotaThresholdCrossed(
        provider: ProviderID,
        bucket: String,
        remainingPercent: Double,
        windowId: String,
        threshold: QuotaThreshold
    )

    /// Fired when a fresh observation shows quota has recovered to approximately full in a new window.
    case quotaReplenished(
        provider: ProviderID,
        bucket: String,
        windowId: String
    )

    /// Fired when an agent session transitions into a notable confirmed lifecycle state.
    case sessionStateTransition(
        session: AgentSession,
        fromState: AgentState,
        toState: AgentState
    )

    /// A stable string identifying the event category.
    public var eventType: String {
        switch self {
        case .quotaThresholdCrossed:
            return "quotaThresholdCrossed"
        case .quotaReplenished:
            return "quotaReplenished"
        case .sessionStateTransition:
            return "sessionStateTransition"
        }
    }

    /// The associated provider, if available.
    public var provider: ProviderID? {
        switch self {
        case .quotaThresholdCrossed(let provider, _, _, _, _):
            return provider
        case .quotaReplenished(let provider, _, _):
            return provider
        case .sessionStateTransition(let session, _, _):
            return session.provider
        }
    }
}
